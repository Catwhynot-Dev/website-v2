const ui = {
  skills: document.getElementById("skills"),
  skillName: document.getElementById("skillName"),
  progress: document.getElementById("progress"),
  currentStep: document.getElementById("currentStep"),
  choices: document.getElementById("choices"),
  feedback: document.getElementById("feedback"),
  score: document.getElementById("score"),
  correctCount: document.getElementById("correctCount"),
  attempts: document.getElementById("attempts"),
  accuracy: document.getElementById("accuracy"),
  overviewList: document.getElementById("overviewList")
};

const state = {
  skillIndex: -1,
  stepIndex: 0,
  score: 0,
  attempts: 0,
  firstTryCorrect: 0,
  missedSteps: new Set()
};

function getSubsteps(stepText) {
  const text = stepText.replace(/\s+/g, " ").trim();
  const parts = text.includes(":")
    ? text.split(":")[1].split(/;|\bOR\b/)
    : text.split(/;|\bOR\b/);

  const cleaned = parts
    .map((part) => part.replace(/^\s*(and|then)\s+/i, "").trim())
    .filter((part) => part.length > 20);

  return cleaned.length > 1 ? cleaned : [];
}

function renderOverview() {
  if (state.skillIndex < 0) {
    ui.overviewList.innerHTML = "";
    return;
  }

  const skill = skills[state.skillIndex];
  const completedSteps = skill.steps.slice(0, state.stepIndex + 1);

  ui.overviewList.innerHTML = "";

  completedSteps.forEach((stepText) => {
    const li = document.createElement("li");
    li.textContent = stepText;

    const substeps = getSubsteps(stepText);
    if (substeps.length) {
      const sub = document.createElement("ol");
      sub.className = "substeps";
      sub.type = "a";

      substeps.forEach((substep) => {
        const subLi = document.createElement("li");
        subLi.textContent = substep;
        sub.appendChild(subLi);
      });

      li.appendChild(sub);
    }

    ui.overviewList.appendChild(li);
  });
}

function buildSkillButtons() {
  skills.forEach((skill, index) => {
    const button = document.createElement("button");
    button.className = "skill-btn";
    button.textContent = skill.name;
    button.addEventListener("click", () => startSkill(index));
    ui.skills.appendChild(button);
  });
}

function startSkill(index) {
  state.skillIndex = index;
  state.stepIndex = 0;
  state.score = 0;
  state.attempts = 0;
  state.firstTryCorrect = 0;
  state.missedSteps = new Set();

  [...ui.skills.children].forEach((button, i) => {
    button.classList.toggle("active", i === index);
  });

  ui.feedback.textContent = "";
  ui.feedback.className = "feedback";
  renderQuestion();
  renderOverview();
  updateScoreboard();
}

function getChoices(skill, stepIndex) {
  const correct = skill.steps[stepIndex + 1];
  const pool = skill.steps.filter((step, i) => i !== stepIndex + 1 && i !== stepIndex);
  const distractors = [];

  let cursor = (stepIndex * 3 + 1) % pool.length;
  while (distractors.length < 3) {
    const candidate = pool[cursor % pool.length];
    if (!distractors.includes(candidate)) distractors.push(candidate);
    cursor += 5;
  }

  const choices = [correct, ...distractors];
  const rotateBy = stepIndex % 4;
  return choices.slice(rotateBy).concat(choices.slice(0, rotateBy));
}

function renderQuestion() {
  if (state.skillIndex < 0) return;
  const skill = skills[state.skillIndex];

  if (state.stepIndex >= skill.steps.length - 1) {
    ui.currentStep.textContent = "Skill complete.";
    ui.progress.textContent = `Completed ${skill.steps.length - 1}/${skill.steps.length - 1}`;
    ui.choices.innerHTML = "";
    ui.feedback.textContent = "✅ Skill finished. Choose another skill to continue practicing.";
    ui.feedback.className = "feedback good";
    return;
  }

  ui.skillName.textContent = skill.name;
  ui.progress.textContent = `Step ${state.stepIndex + 1}/${skill.steps.length - 1}`;
  ui.currentStep.textContent = skill.steps[state.stepIndex];
  ui.choices.innerHTML = "";

  getChoices(skill, state.stepIndex).forEach((choice) => {
    const btn = document.createElement("button");
    btn.className = "choice";
    btn.textContent = choice;
    btn.addEventListener("click", () => submitAnswer(choice));
    ui.choices.appendChild(btn);
  });
}

function submitAnswer(selected) {
  const skill = skills[state.skillIndex];
  const currentIdx = state.stepIndex;
  const correct = skill.steps[currentIdx + 1];

  state.attempts += 1;

  if (selected === correct) {
    if (!state.missedSteps.has(currentIdx)) {
      state.firstTryCorrect += 1;
      state.score += 10;
    }

    state.stepIndex += 1;
    ui.feedback.textContent = "Correct! Moving to the next step.";
    ui.feedback.className = "feedback good";
    renderQuestion();
    renderOverview();
  } else {
    state.missedSteps.add(currentIdx);
    ui.feedback.textContent = "Not quite. Review the current step and try again.";
    ui.feedback.className = "feedback bad";
  }

  updateScoreboard();
}

function updateScoreboard() {
  const completedSteps = state.stepIndex;
  const accuracy = completedSteps === 0 ? 0 : Math.round((state.firstTryCorrect / completedSteps) * 100);

  ui.score.textContent = String(state.score);
  ui.correctCount.textContent = String(state.firstTryCorrect);
  ui.attempts.textContent = String(state.attempts);
  ui.accuracy.textContent = `${accuracy}%`;
}

